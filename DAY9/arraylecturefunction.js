let name = ["Rohan", "Vivek", "Ajay"]

    console.log(name);

    console.log(name[1]);

    console.log(name.length);
    
    // push: Adds an element at the end.
    name.push("Rahul");
    console.log(name);
    
    // pop: Removes the last element.
    name.pop();
    console.log(name);

    // unshift: Adds an element at the beginning.
    name.unshift("Rohit");
    console.log(name);

    // shift: Removes the first element.
    name.shift();
    console.log(name);

    // reverse: Reverses the array's direction.
    name.reverse();
    console.log(name);
    
    let rollno = [2, 45, 67, 37, 99]
    rollno.reverse();
    console.log(rollno);

    // includes: Checks whether an element exists within the array.
    console.log(name.includes("Arya"));
    